CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(32) NOT NULL,
    username_normalized VARCHAR(32) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    profile_picture_url VARCHAR(1024),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    disabled_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT ux_users_username_normalized UNIQUE (username_normalized)
);

CREATE TABLE conversations (
    id UUID PRIMARY KEY,
    type VARCHAR(16) NOT NULL,
    title VARCHAR(200),
    direct_pair_key VARCHAR(64),
    created_by BIGINT NOT NULL REFERENCES users(id),
    last_message_id UUID,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT ck_conversations_type CHECK (type IN ('DIRECT', 'GROUP')),
    CONSTRAINT ck_conversations_direct_pair
        CHECK ((type = 'DIRECT' AND direct_pair_key IS NOT NULL)
            OR (type = 'GROUP' AND direct_pair_key IS NULL)),
    CONSTRAINT ux_conversations_direct_pair UNIQUE (direct_pair_key)
);

CREATE INDEX ix_conversations_created_by ON conversations(created_by);

CREATE TABLE conversation_members (
    conversation_id UUID NOT NULL REFERENCES conversations(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    role VARCHAR(16) NOT NULL,
    joined_at TIMESTAMP WITH TIME ZONE NOT NULL,
    left_at TIMESTAMP WITH TIME ZONE,
    last_read_sequence BIGINT,
    last_read_message_id UUID,
    last_read_at TIMESTAMP WITH TIME ZONE,
    read_receipts_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_conversation_members PRIMARY KEY (conversation_id, user_id),
    CONSTRAINT ck_conversation_members_role CHECK (role IN ('OWNER', 'ADMIN', 'MEMBER'))
);

CREATE INDEX ix_cm_user_conversation ON conversation_members(user_id, conversation_id);

CREATE TABLE messages (
    id UUID PRIMARY KEY,
    conversation_id UUID NOT NULL REFERENCES conversations(id),
    sequence BIGINT NOT NULL,
    sender_id BIGINT NOT NULL REFERENCES users(id),
    body TEXT,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    edited_at TIMESTAMP WITH TIME ZONE,
    deleted_at TIMESTAMP WITH TIME ZONE,
    reply_to_message_id UUID REFERENCES messages(id),
    client_message_id UUID NOT NULL,
    version INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT ux_messages_conversation_sequence UNIQUE (conversation_id, sequence),
    CONSTRAINT ux_messages_sender_client_id UNIQUE (sender_id, client_message_id)
);

CREATE INDEX ix_messages_sender_created ON messages(sender_id, created_at);
CREATE INDEX ix_messages_reply_to ON messages(reply_to_message_id);

CREATE TABLE message_attachments (
    id UUID PRIMARY KEY,
    message_id UUID NOT NULL REFERENCES messages(id),
    object_key VARCHAR(1024) NOT NULL,
    media_type VARCHAR(255) NOT NULL,
    byte_size BIGINT NOT NULL,
    checksum VARCHAR(128),
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX ix_attachments_message ON message_attachments(message_id);

CREATE TABLE message_receipts (
    message_id UUID NOT NULL REFERENCES messages(id),
    user_id BIGINT NOT NULL REFERENCES users(id),
    delivered_at TIMESTAMP WITH TIME ZONE,
    read_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT pk_message_receipts PRIMARY KEY (message_id, user_id)
);

CREATE INDEX ix_receipts_user_message ON message_receipts(user_id, message_id);

CREATE TABLE notifications (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    conversation_id UUID REFERENCES conversations(id),
    message_id UUID REFERENCES messages(id),
    type VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    read_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_notifications_user_read_created
    ON notifications(user_id, read_at, created_at);

CREATE TABLE outbox_events (
    id UUID PRIMARY KEY,
    aggregate_type VARCHAR(100) NOT NULL,
    aggregate_id UUID NOT NULL,
    event_type VARCHAR(150) NOT NULL,
    payload JSONB NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMP WITH TIME ZONE
);

CREATE INDEX ix_outbox_events_pending
    ON outbox_events(published_at, next_attempt_at, created_at);

CREATE TABLE refresh_tokens (
    id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    token_hash VARCHAR(128) NOT NULL,
    expires_at TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITH TIME ZONE,
    replaced_by_token_id UUID REFERENCES refresh_tokens(id),
    CONSTRAINT ux_refresh_tokens_token_hash UNIQUE (token_hash)
);

CREATE INDEX ix_refresh_tokens_user_id ON refresh_tokens(user_id);
